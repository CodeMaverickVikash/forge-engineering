import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { check, extractComments, checkComments } from '../../skills/forge/scripts/comment-check.mjs';

const SCRIPT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../skills/forge/scripts/comment-check.mjs');
const lines = (s) => s.split('\n').map((text, i) => ({ line: i + 1, text }));
const rules = (file, src) => checkComments(file, extractComments(file, lines(src))).map((f) => `${f.line}:${f.rule}`);

test('the standard\'s good examples pass', () => {
  const good = [
    '// Keep the latest request to avoid stale search results.',
    'const latestRequest = requestId;',
    '// Retry once when the service is temporarily unavailable.',
    '// Normalize the email before checking for duplicates.',
    '// Use UTC here because billing dates are shared across time zones.',
    '// Keep this check before payment creation to prevent duplicate charges.',
    '/**',
    ' * Returns the final price after applying eligible discounts.',
    ' */',
    'function calculateFinalPrice() {}',
    'const url = "https://example.com"; // Sandbox host; production comes from config.',
    '// eslint-disable-next-line no-console',
  ].join('\n');
  assert.deepEqual(rules('src/a.ts', good), []);
  assert.deepEqual(rules('app/b.py', 'def calculate_final_price():\n    """Apply eligible discounts to the original price."""\n'), []);
});

test('the standard\'s bad examples and prohibited patterns are errors', () => {
  const bad = [
    '// This variable is used to store the latest request ID.',          // 1
    '// This function is responsible for fetching the data from the API.', // 2
    '// This class is used for handling user-related database operations.', // 3
    '// Here we are checking if the user is authenticated or not.',       // 4
    "// Let's understand what happens here.",                              // 5
    '// Increment counter',                                                // 6
    '// ==================== Helpers ====================',                // 7
    '// Generated by Claude',                                              // 8
    '// Fast path 🚀',                                                    // 9
    '// console.log(user);',                                               // 10
    '// TODO:',                                                            // 11
  ].join('\n');
  // The examples are stacked into one block, which is itself a long-block warning; that is tested separately.
  assert.deepEqual(rules('src/a.ts', bad).filter((r) => !r.endsWith(':long')), [
    '1:restates-code', '2:restates-code', '3:restates-code', '4:narration', '5:narration', '6:obvious',
    '7:banner', '8:ai-mention', '9:emoji', '10:commented-out-code', '11:todo-empty',
  ]);
  assert.deepEqual(rules('job.py', '# This function normalizes the email address.\nx = 1  # Now we update the cache\n'), ['1:restates-code', '2:narration']);
  assert.deepEqual(rules('q.sql', '-- ---------------------\nSELECT 1;\n'), ['1:banner']);
});

test('genuine TODOs, promotional wording and long blocks are warnings, not errors', () => {
  const src = [
    '// TODO: Add pagination when the API supports cursor-based queries (ENG-142).',
    '// Blazing fast lookup.',
    '',
    ...Array.from({ length: 8 }, (_, i) => `// Line ${i + 1} of a long explanation.`),
  ].join('\n');
  const f = checkComments('a.js', extractComments('a.js', lines(src)));
  assert.deepEqual(f.map((x) => `${x.line}:${x.rule}:${x.level}`), ['1:todo:warn', '2:promotional:warn', '4:long:warn']);
});

test('only comments the change adds are checked; existing comments are left alone', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-cc-'));
  try {
    const g = (...a) => execFileSync('git', ['-c', 'core.autocrlf=false', ...a], { cwd: dir, stdio: 'pipe' });
    g('init', '-q');
    fs.writeFileSync(path.join(dir, 'old.js'), '// This function is responsible for legacy things.\nfunction legacy() {}\n');
    fs.writeFileSync(path.join(dir, 'README.md'), '# This function is documented in prose\n');
    g('add', '.'); g('-c', 'user.name=t', '-c', 'user.email=t@example.invalid', 'commit', '-qm', 'base');

    fs.appendFileSync(path.join(dir, 'old.js'), '// Retry once when the cache is cold.\nfunction warm() {}\n// This method is used to warm the cache.\n');
    fs.writeFileSync(path.join(dir, 'new.py'), '# Written by an AI assistant\nx = 1\n');
    fs.appendFileSync(path.join(dir, 'README.md'), '\n# Let\'s begin\n');
    const r = check(dir);
    assert.deepEqual(r.findings.map((f) => `${f.file}:${f.line}:${f.rule}`), ['old.js:5:restates-code', 'new.py:1:ai-mention']);
    assert.equal(r.errors, 2);

    const cli = spawnSync(process.execPath, [SCRIPT, '--root', dir], { encoding: 'utf8' });
    assert.equal(cli.status, 1);
    assert.match(cli.stdout, /ERROR old\.js:5 \[restates-code\]/);
    assert.match(cli.stdout, /Comment check FAILED/);

    const files = spawnSync(process.execPath, [SCRIPT, '--root', dir, '--files', 'old.js'], { encoding: 'utf8' });
    assert.match(files.stdout, /old\.js:1 \[restates-code\]/, '--files checks whole files');
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
});

test('CLI reports a non-git folder without a stack trace', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'forge-cc-nogit-'));
  try {
    const r = spawnSync(process.execPath, [SCRIPT, '--root', dir], { encoding: 'utf8' });
    assert.equal(r.status, 2);
    assert.match(r.stderr, /UNAVAILABLE/);
    assert.doesNotMatch(r.stderr, /at .*\.mjs:\d+/);
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
});
